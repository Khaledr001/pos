import type { BadgeIcon } from "@devsfleet/shared-types";
import {
  Award,
  BadgeCheck,
  Briefcase,
  Building2,
  ChartColumn,
  Clock,
  CreditCard,
  Droplet,
  Globe,
  Hammer,
  Headset,
  Heart,
  Leaf,
  Lightbulb,
  Lock,
  Mail,
  MapPin,
  Package,
  Phone,
  RefreshCw,
  Ruler,
  ShieldCheck,
  Star,
  ThumbsUp,
  Truck,
  Users,
  Wrench,
  Zap,
  type LucideIcon,
} from "lucide-react";

/** Every icon a feature or trust badge may name. The closed set lives in shared-types. */
const ICONS: Record<BadgeIcon, LucideIcon> = {
  truck: Truck,
  shield: ShieldCheck,
  "badge-check": BadgeCheck,
  headset: Headset,
  refresh: RefreshCw,
  "credit-card": CreditCard,
  clock: Clock,
  package: Package,
  star: Star,
  leaf: Leaf,
  wrench: Wrench,
  hammer: Hammer,
  building: Building2,
  users: Users,
  award: Award,
  phone: Phone,
  mail: Mail,
  "map-pin": MapPin,
  globe: Globe,
  heart: Heart,
  lightbulb: Lightbulb,
  ruler: Ruler,
  zap: Zap,
  droplet: Droplet,
  briefcase: Briefcase,
  chart: ChartColumn,
  lock: Lock,
  "thumbs-up": ThumbsUp,
};

/** A name from a newer API than this build knows still renders: it falls back to a tick. */
export function badgeIcon(name: string | undefined): LucideIcon {
  return (name && (ICONS as Record<string, LucideIcon | undefined>)[name]) || BadgeCheck;
}
